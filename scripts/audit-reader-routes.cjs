const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
function walk(dir) { return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(path.join(dir, entry.name)) : [path.join(dir, entry.name)]); }
const routes = walk('src/app').filter(file => file.endsWith('.tsx'));
const report = [];
let duplicates = 0;
for (const file of [...routes, ...walk('src/components').filter(file => file.endsWith('.tsx'))]) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const tables = new Set(); const rpcs = new Set(); const fixed = [];
  function visit(node) {
    if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && ts.isStringLiteral(node.arguments[0] ?? {})) {
      if (node.expression.name.text === 'from') tables.add(node.arguments[0].text);
      if (node.expression.name.text === 'rpc') rpcs.add(node.arguments[0].text);
    }
    if (ts.isObjectLiteralExpression(node)) {
      const seen = new Set();
      for (const prop of node.properties) {
        const name = prop.name?.getText(source);
        if (name && seen.has(name)) { duplicates++; console.error(`${file}:${source.getLineAndCharacterOfPosition(prop.pos).line + 1}: duplicate ${name}`); }
        seen.add(name);
        if (name === 'width' && ts.isPropertyAssignment(prop) && ts.isNumericLiteral(prop.initializer) && Number(prop.initializer.text) > 200) fixed.push(prop.getText(source));
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  report.push(`- ${file}: ${source.getLineAndCharacterOfPosition(source.end).line + 1} lines; tables/storage: ${[...tables].join(', ') || 'none'}; RPC: ${[...rpcs].join(', ') || 'none'}; wide fixed widths: ${fixed.join(', ') || 'none'}`);
}
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/reader-route-audit.md', '# Route and component audit\n\nGenerated by `node scripts/audit-reader-routes.cjs`. Reads every TSX route/component using the TypeScript parser; does not modify source.\n\n' + report.join('\n') + `\n\nDuplicate object properties: ${duplicates}\n`);
console.log(`${routes.length} routes inspected; ${duplicates} duplicate object properties.`);
process.exitCode = duplicates ? 1 : 0;
